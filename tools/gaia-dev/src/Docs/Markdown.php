namespace GaiaDev\Docs;

/**
 * Builds the generated pages out of sections that stay short and keep a stable
 * anchor, so one section can be served on its own. A section is an anchor line,
 * a heading, a blank line and at most BODY_LINES lines; a longer body is split
 * into numbered parts, repeating the table header when the body is a table.
 *
 * @author Hammad Hassan <gollomer@gmail.com>
 * @package GaiaDev\Docs
 * @license http://www.gnu.org/licenses/agpl.html AGPLv3
 */
class Markdown
{
    /**
     * A section (anchor, heading, blank line and body) is at most this many lines.
     */
    public const SECTION_LINES = 40;

    private const BODY_LINES = 36;

    /**
     * @param string $title
     * @param string $source what the page is generated from, shown under the title
     * @return string[]
     */
    public static function page(string $title, string $source): array
    {
        return ['# ' . $title, '', '> Generated by `gaia-dev docs generate` from ' . $source . '. Do not edit.', ''];
    }

    /**
     * @param string $heading
     * @param string[] $body lines; a leading table header (two lines starting with |) is repeated per part
     * @param int $level heading level
     * @return string[] lines of one or more sections
     */
    public static function section(string $heading, array $body, int $level = 2): array
    {
        $header = [];
        if (count($body) > 2 && strpos($body[0], '|') === 0 && strpos($body[1], '|') === 0) {
            $header = array_splice($body, 0, 2);
        }
        $parts = $body ? array_chunk($body, self::BODY_LINES - count($header)) : [[]];

        $lines = [];
        foreach ($parts as $index => $part) {
            $title = count($parts) > 1 ? $heading . ' (' . ($index + 1) . '/' . count($parts) . ')' : $heading;
            $lines[] = '<a id="' . self::slug($title) . '"></a>';
            $lines[] = str_repeat('#', $level) . ' ' . $title;
            $lines[] = '';
            foreach (array_merge($header, $part) as $line) {
                $lines[] = $line;
            }
            $lines[] = '';
        }

        return $lines;
    }

    /**
     * @param string $text
     * @return string stable anchor: lower case, words joined with -
     */
    public static function slug(string $text): string
    {
        return trim(preg_replace('/[^a-z0-9]+/', '-', strtolower($text)), '-');
    }

    /**
     * @param string[] $headers
     * @param string[][] $rows
     * @return string[] table lines
     */
    public static function table(array $headers, array $rows): array
    {
        $lines = ['| ' . implode(' | ', $headers) . ' |', '|' . str_repeat('---|', count($headers))];
        foreach ($rows as $row) {
            $lines[] = '| ' . implode(' | ', array_map(function ($cell) {
                return str_replace(['|', "\n"], ['\\|', ' '], $cell);
            }, $row)) . ' |';
        }

        return $lines;
    }

    /**
     * @param string[] $lines
     * @return string the page body, LF line endings and one trailing newline
     */
    public static function render(array $lines): string
    {
        return rtrim(implode("\n", $lines)) . "\n";
    }
}
