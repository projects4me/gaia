namespace Gaia\Libraries\Oauth\Storage;

/**
 * This class extends Pdo class provided by bshaffer/oauth2-server-php library. In this class we're overriding
 * checkPassword and hashPassword method in order to follow our hashing functionality. By default hashPassword method
 * use "sha1" algorithm in order to match user password. But we have changed the encryption of user password using
 * "bcrypt" alogrithm to add more security. So now we need to match the hash generated by bcrypt algorithm. That's why
 * we needed to override these methods.
 * 
 * @author Rana Nouman <ranamnouman@gmail.com>
 */
class Pdo extends \OAuth2\Storage\Pdo
{
    /**
     * Whether the session the next refresh token belongs to is a Remember Me session.
     *
     * @var bool
     */
    private $sessionRememberMe = false;

    /**
     * When the session the next refresh token belongs to ends (UTC).
     *
     * @var string|null
     */
    private $sessionExpires = null;

    /**
     * Fetches a user record by email address instead of username.
     *
     * bshaffer passes whatever was supplied as "username" in the token request
     * straight into this method. Because we accept an email field from the
     * client and remap it to "username" before the grant type runs, the value
     * arriving here is always an email address.
     *
     * user_id is set to the email so that the access-token row carries the
     * email; RestController resolves the current user with:
     *   User::findFirst("email = '$token->user_id'")
     *
     * @param  string $email
     * @return array|false
     */
    public function getUser($email)
    {
        $stmt = $this->db->prepare(
            sprintf('SELECT * FROM %s WHERE email = :email', $this->config['user_table'])
        );
        $stmt->execute(['email' => $email]);

        if (!$userInfo = $stmt->fetch(\PDO::FETCH_ASSOC)) {
            return false;
        }

        return array_merge(['user_id' => $userInfo['email']], $userInfo);
    }

    /**
     * Checks a client secret against the stored one.
     *
     * Agent clients store a password_hash() of their secret (see
     * `AgentCredentials`); other clients keep the plain secret, compared in
     * constant time.
     *
     * @param string      $client_id
     * @param string|null $client_secret
     * @return bool
     */
    public function checkClientCredentials($client_id, $client_secret = null)
    {
        $stmt = $this->db->prepare(sprintf(
            'SELECT client_secret, previous_client_secret, previous_secret_expires FROM %s WHERE client_id = :client_id',
            $this->config['client_table']
        ));
        $stmt->execute(['client_id' => $client_id]);
        $row = $stmt->fetch(\PDO::FETCH_ASSOC);

        if ($row === false || $client_secret === null) {
            return false;
        }

        if ($this->secretMatches($row['client_secret'], $client_secret)) {
            return true;
        }

        // A rotated secret's previous one is accepted until its grace period
        // ends (ServiceClientSecrets, D-068).
        return $this->isGraceSecretLive($row['previous_secret_expires'])
            && $this->secretMatches($row['previous_client_secret'], $client_secret);
    }

    /**
     * Whether a previous secret's grace period, stored as a UTC datetime, is
     * still running.
     *
     * @param  string|null $expires
     * @return bool
     */
    protected function isGraceSecretLive($expires)
    {
        if ($expires === null || $expires === '') {
            return false;
        }

        $expiresAt = strtotime($expires . ' UTC');
        return $expiresAt !== false && $expiresAt > time();
    }

    /**
     * Whether a secret matches the stored one: a password_hash() is verified,
     * a plain secret compared in constant time.
     *
     * @param  string|null $stored
     * @param  string      $client_secret
     * @return bool
     */
    protected function secretMatches($stored, $client_secret)
    {
        if ($stored === null) {
            return false;
        }

        $hashInfo = password_get_info($stored);
        if (!empty($hashInfo['algo'])) {
            return password_verify((string) $client_secret, $stored);
        }

        return hash_equals((string) $stored, (string) $client_secret);
    }

    /**
     * This function checks user password.
     *
     * @param array $user
     * @param string $password
     * @return string
     */
    protected function checkPassword($user, $password)
    {
        return $user['password'] = $this->hashPassword($password, $user['password']);
    }

    /**
     * This function matches stored hash of the password with the password input by user.
     *
     * @param string $password  Input given by user.
     * @param string $passwordHash  Hash of password stored in database.
     * @return string
     */
    protected function hashPassword($password, $passwordHash = null)
    {
        if (password_verify($password, $passwordHash)) {
            return $passwordHash;
        }
    }

    /**
     * Whether the client may use the grant type: its `grant_types` list, or
     * the grants its kind may always use (config `kind_grant_types`, kind =>
     * grant types; `OAuthServer` sets it, e.g. service clients and the
     * agent-delegation grant, whose own checks decide the rest).
     *
     * @param  string $client_id
     * @param  string $grant_type
     * @return bool
     */
    public function checkRestrictedGrantType($client_id, $grant_type)
    {
        $kindGrants = isset($this->config['kind_grant_types']) ? (array) $this->config['kind_grant_types'] : [];
        $details = $this->getClientDetails($client_id);
        $kind = is_array($details) && isset($details['kind']) ? (string) $details['kind'] : '';
        if ($kind !== '' && isset($kindGrants[$kind]) && in_array($grant_type, (array) $kindGrants[$kind], true)) {
            return true;
        }

        return parent::checkRestrictedGrantType($client_id, $grant_type);
    }

    /**
     * Sets the session window that the next refresh token stored by this
     * request carries (see `Gaia\Libraries\Authorization\SessionExpiry`).
     *
     * @param  bool        $rememberMe
     * @param  string|null $sessionExpires UTC, `Y-m-d H:i:s`.
     * @return void
     */
    public function setSessionWindow($rememberMe, $sessionExpires)
    {
        $this->sessionRememberMe = (bool) $rememberMe;
        $this->sessionExpires = $sessionExpires;
    }

    /**
     * Stores a refresh token with the session window set by `setSessionWindow`,
     * so each session keeps its own expiry instead of the user's.
     *
     * @param  string $refresh_token
     * @param  mixed  $client_id
     * @param  mixed  $user_id
     * @param  int    $expires
     * @param  string $scope
     * @return bool
     */
    public function setRefreshToken($refresh_token, $client_id, $user_id, $expires, $scope = null)
    {
        $expires = date('Y-m-d H:i:s', $expires);
        $rememberMe = $this->sessionRememberMe ? 1 : 0;
        $sessionExpires = $this->sessionExpires;

        $stmt = $this->db->prepare(sprintf(
            'INSERT INTO %s (refresh_token, client_id, user_id, expires, scope, "rememberMe", "sessionExpires") '
            . 'VALUES (:refresh_token, :client_id, :user_id, :expires, :scope, :rememberMe, :sessionExpires)',
            $this->config['refresh_token_table']
        ));

        return $stmt->execute(
            compact('refresh_token', 'client_id', 'user_id', 'expires', 'scope', 'rememberMe', 'sessionExpires')
        );
    }
}