namespace Gaia\MVC\Models\Behaviors;

use Gaia\Libraries\Workspaces\AgentWorkspace;
use Phalcon\Messages\Message;
use Phalcon\Mvc\ModelInterface;
use Phalcon\Mvc\Model\BehaviorInterface;
use Phalcon\Mvc\Model\Behavior;

/**
 * A membership of an agent user may only be created in a project of the
 * agent's workspace (Workspaces D-006). The rule lives in
 * {@see AgentWorkspace}.
 *
 * @author Hammad Hassan <gollomer@gmail.com>
 * @package Foundation
 * @category Behavior
 * @license http://www.gnu.org/licenses/agpl.html AGPLv3
 */
class membershipAgentWorkspaceBehavior extends Behavior implements BehaviorInterface
{
    /**
     * Returning false from a before* event cancels the save.
     *
     * @param  string         $eventType
     * @param  ModelInterface $model
     * @return mixed
     */
    public function notify($eventType, ModelInterface $model)
    {
        if (method_exists($this, $eventType)) {
            return $this->$eventType($model);
        }
    }

    /**
     * @param  ModelInterface $model
     * @return bool
     */
    protected function beforeValidationOnCreate($model)
    {
        $allowed = (new AgentWorkspace())->mayWorkIn(
            $model->readAttribute('userId'),
            $model->readAttribute('projectId')
        );
        if ($allowed) {
            return true;
        }

        $model->appendMessage(new Message(AgentWorkspace::MEMBERSHIP_OUTSIDE, 'projectId', 'InvalidValue'));
        return false;
    }
}
